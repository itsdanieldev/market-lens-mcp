"""사용자가 클라이언트 메뉴에서 고르는 MCP 프롬프트의 문구.

도구를 부를지는 모델이 정하므로 같은 질문에도 도구를 쓰지 않을 때가 있다. 프롬프트는
사용자가 직접 고르는 것이라, 어떤 도구를 어떤 순서로 쓸지 문구에 못 박아 둘 수 있다.
여기서는 문구만 만들고 등록은 server.py가 한다.
"""

from __future__ import annotations

# 모든 프롬프트 끝에 붙는 공통 규칙. 서버 안내문(server.INSTRUCTIONS)과 같은 내용이다.
RULES = """\
규칙:
- 숫자는 도구 응답 값만 쓰고, 증감률·수익률은 직접 계산하지 말고 응답의 computed 값을 씁니다.
- 기억이나 웹 검색으로 숫자를 채우지 않습니다. 도구가 주지 않은 내용은 모른다고 적습니다.
- 사실 정리와 설명만 합니다. 매수·매도 의견, 목표가, 종목 추천은 쓰지 않습니다.
- 답변 끝에 사용한 도구 응답마다 citation(출처·기준일)을 그대로 적습니다.
- 도구 응답의 warnings에 내용이 있으면 답변에 함께 알립니다."""


def stock_briefing(company: str) -> str:
    """실적, 공시, 주가를 한 번에 정리하는 종목 브리핑 문구를 만든다.

    Args:
        company: 종목명 또는 6자리 종목코드.

    Returns:
        도구 5개를 쓰는 순서와 답변 형식을 지시하는 프롬프트.
    """
    return f"""\
market-lens 도구로 {company}의 종목 브리핑을 만들어 주세요.

순서:
1. resolve_ticker로 종목을 확인합니다. 하나로 확정되지 않으면 후보를 보여 주고 멈춥니다.
2. get_financials로 가장 최근 분기 실적을 조회합니다. 자료가 없다고 나오면 한 분기씩 앞으로 가며 다시 조회합니다.
3. list_disclosures로 최근 30일 공시 목록을 조회합니다.
4. 실적이나 경영에 영향이 큰 공시가 있으면 get_disclosure_text로 본문을 읽습니다(최대 2건).
5. get_stock_prices로 최근 90일 주가를 조회합니다.

답변 형식:
- 실적: 매출, 영업이익, 순이익과 전년 동기 대비 증감률, 이익률을 표로 정리합니다.
- 공시: 날짜순으로 주요 공시를 정리하고, 본문을 읽은 공시는 핵심을 요약합니다.
- 주가: 기간 수익률, 기간 고가·저가와 날짜, 최근 흐름을 정리합니다.

{RULES}"""


def earnings_review(company: str, period: str = "") -> str:
    """한 분기 또는 한 해의 실적을 자세히 보는 문구를 만든다.

    Args:
        company: 종목명 또는 6자리 종목코드.
        period: '2026년 3분기', '2025년 연간' 같은 대상 기간. 비우면 가장 최근 분기.

    Returns:
        실적 조회와 근거 보고서 확인을 지시하는 프롬프트.
    """
    target = period.strip() or "가장 최근 분기"
    return f"""\
market-lens 도구로 {company}의 {target} 실적을 정리해 주세요.

순서:
1. get_financials로 해당 기간의 실적을 조회합니다. 연간이면 quarter=4로 조회합니다.
   기간을 정하지 않았고 자료가 없다고 나오면 한 분기씩 앞으로 가며 다시 조회합니다.
2. 응답의 rcept_no(근거 보고서의 접수번호)로 get_disclosure_text를 불러 보고서 앞부분을 읽고,
   실적 변동의 배경으로 회사가 설명한 내용이 있으면 정리합니다.

답변 형식:
- 손익: 매출, 영업이익, 순이익의 당기 금액, 비교 금액, 증감률. 분기면 누적 금액과 누적 증감률도 적습니다.
- 수익성과 재무: 영업이익률, 순이익률, 부채비율, 자산·부채·자본의 증감률.
- 배경: 보고서에서 확인한 내용만 적고, 확인하지 못했으면 그렇게 적습니다.

{RULES}"""


def disclosure_digest(company: str, days: str = "30") -> str:
    """최근 공시를 훑어 중요한 것만 요약하는 문구를 만든다.

    Args:
        company: 종목명 또는 6자리 종목코드.
        days: 오늘부터 며칠 전까지 볼지. 숫자가 아니면 30일로 본다.

    Returns:
        공시 목록 조회와 본문 확인을 지시하는 프롬프트.
    """
    span = days.strip() if days.strip().isdigit() else "30"
    return f"""\
market-lens 도구로 {company}의 최근 {span}일 공시를 정리해 주세요.

순서:
1. list_disclosures로 최근 {span}일 공시 목록을 조회합니다. has_more가 true면 limit을 늘려 다시 조회합니다.
2. 공시를 종류별로 묶습니다(정기보고서, 주요사항, 지분 변동, 거래소 공시 등).
3. 정기보고서와 주요사항 가운데 중요한 공시는 get_disclosure_text로 본문을 읽습니다(최대 3건).

답변 형식:
- 요약: 기간 안의 전체 건수와 종류별 건수.
- 주요 공시: 날짜, 제목, 본문에서 확인한 핵심 내용, DART 링크(url).
- 나머지: 임원·주요주주 소유상황보고서처럼 반복되는 공시는 건수만 적습니다.

{RULES}"""
